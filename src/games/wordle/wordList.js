const answerSet = new Set(
  RAW_ANSWER_WORDS.trim()
    .split(/\s+/)
    .map((w) => w.trim().toUpperCase())
    .filter((w) => /^[A-Z]{5}$/.test(w))
);

const extraSet = new Set(
  RAW_EXTRA_GUESSES.trim()
    .split(/\s+/)
    .map((w) => w.trim().toUpperCase())
    .filter((w) => /^[A-Z]{5}$/.test(w))
);

export const ANSWER_WORDS = Array.from(answerSet);
export const VALID_GUESS_SET = new Set([...answerSet, ...extraSet]);

/**
 * Compute a player-friendliness / letter-rate score for a 5-letter word.
 * Higher score = composed of high-frequency English letters, distinct letters, and balanced vowels.
 * @param {string} word
 */
export function computeLetterRateScore(word) {
  const letters = word.toUpperCase().split('');
  const unique = new Set(letters);

  let freqSum = 0;
  let rareCount = 0;
  let vowelCount = 0;

  for (const ch of letters) {
    freqSum += LETTER_FREQUENCY[ch] || 0.2;
    if (RARE_LETTERS.has(ch)) rareCount += 1;
    if (VOWELS.has(ch)) vowelCount += 1;
  }

  // Average letter frequency in [~2, ~9.5], scaled nicely
  let score = freqSum / 5;

  // Distinct letters dramatically improve Wordle information gain
  if (unique.size === 5) {
    score *= 1.38;
  } else if (unique.size === 4) {
    score *= 0.82;
  } else {
    score *= 0.45;
  }

  // 2 vowels is the easiest standard Wordle pattern
  if (vowelCount === 2) {
    score *= 1.16;
  } else if (vowelCount === 1 || vowelCount === 3) {
    score *= 1.0;
  } else {
    score *= 0.6;
  }

  // Heavy penalty for rare letters (Q, Z, X, J, V, K)
  if (rareCount > 0) {
    score *= Math.pow(0.32, rareCount);
  }

  return score;
}

export const SCORED_ANSWERS = ANSWER_WORDS.map((word) => {
  const uniqueCount = new Set(word).size;
  const hasRare = [...word].some((ch) => RARE_LETTERS.has(ch));
  return {
    word,
    score: computeLetterRateScore(word),
    uniqueCount,
    hasRare,
  };
}).sort((a, b) => b.score - a.score);

export function isValidGuess(word) {
  return VALID_GUESS_SET.has(String(word).toUpperCase());
}
